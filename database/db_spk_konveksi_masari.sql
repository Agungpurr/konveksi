CREATE DATABASE IF NOT EXISTS `db_spk_konveksi_masari` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `db_spk_konveksi_masari`;

DROP TABLE IF EXISTS `riwayat_hasil`;
DROP TABLE IF EXISTS `nilai_alternatif`;
DROP TABLE IF EXISTS `sub_kriteria`;
DROP TABLE IF EXISTS `bahan`;
DROP TABLE IF EXISTS `kriteria`;
DROP TABLE IF EXISTS `users`;

-- 1. Tabel users
CREATE TABLE `users` (
    `id_user` INT AUTO_INCREMENT PRIMARY KEY,
    `nama_lengkap` VARCHAR(100) NOT NULL,
    `username` VARCHAR(50) NOT NULL UNIQUE,
    `password` VARCHAR(255) NOT NULL,
    `role` ENUM('admin', 'pemilik') NOT NULL DEFAULT 'admin',
    `telepon` VARCHAR(20) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 2. Tabel kriteria (8 Kriteria)
CREATE TABLE `kriteria` (
    `id_kriteria` INT AUTO_INCREMENT PRIMARY KEY,
    `kode_kriteria` VARCHAR(10) NOT NULL UNIQUE,
    `nama_kriteria` VARCHAR(100) NOT NULL,
    `jenis` ENUM('benefit', 'cost') NOT NULL,
    `bobot` DECIMAL(8, 4) NOT NULL,
    `bobot_normalisasi` DECIMAL(8, 4) NULL,
    `keterangan` TEXT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 3. Tabel sub_kriteria (Skala Kripsin 1 - 5)
CREATE TABLE `sub_kriteria` (
    `id_sub` INT AUTO_INCREMENT PRIMARY KEY,
    `id_kriteria` INT NOT NULL,
    `nama_sub` VARCHAR(150) NOT NULL,
    `nilai_skala` DECIMAL(5, 2) NOT NULL,
    `keterangan` VARCHAR(255) NULL,
    FOREIGN KEY (`id_kriteria`) REFERENCES `kriteria`(`id_kriteria`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. Tabel bahan (100 Alternatif Bahan Baku Kain)
CREATE TABLE `bahan` (
    `id_bahan` INT AUTO_INCREMENT PRIMARY KEY,
    `kode_bahan` VARCHAR(10) NOT NULL UNIQUE,
    `nama_bahan` VARCHAR(100) NOT NULL,
    `deskripsi` TEXT NULL,
    `foto` VARCHAR(255) NULL,
    `harga_referensi` DECIMAL(12, 2) NULL,
    `status` ENUM('Aktif', 'Nonaktif') DEFAULT 'Aktif',
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 5. Tabel nilai_alternatif (Matriks Keputusan X: 100 x 8 = 800 Nilai)
CREATE TABLE `nilai_alternatif` (
    `id_nilai` INT AUTO_INCREMENT PRIMARY KEY,
    `id_bahan` INT NOT NULL,
    `id_kriteria` INT NOT NULL,
    `nilai` DECIMAL(10, 4) NOT NULL,
    FOREIGN KEY (`id_bahan`) REFERENCES `bahan`(`id_bahan`) ON DELETE CASCADE,
    FOREIGN KEY (`id_kriteria`) REFERENCES `kriteria`(`id_kriteria`) ON DELETE CASCADE,
    UNIQUE KEY `unik_bahan_kriteria` (`id_bahan`, `id_kriteria`)
) ENGINE=InnoDB;

-- 6. Tabel riwayat_hasil (Snapshot Hasil Perhitungan & Kuota)
CREATE TABLE `riwayat_hasil` (
    `id_riwayat` INT AUTO_INCREMENT PRIMARY KEY,
    `id_user` INT NOT NULL,
    `tanggal_hitung` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `kuota_terpilih` INT DEFAULT 10,
    `id_bahan_terbaik` INT NOT NULL,
    `skor_terbaik` DECIMAL(6, 5) NOT NULL,
    `catatan` TEXT NULL,
    `data_json` LONGTEXT NULL,
    FOREIGN KEY (`id_user`) REFERENCES `users`(`id_user`) ON DELETE CASCADE,
    FOREIGN KEY (`id_bahan_terbaik`) REFERENCES `bahan`(`id_bahan`) ON DELETE CASCADE
) ENGINE=InnoDB;

